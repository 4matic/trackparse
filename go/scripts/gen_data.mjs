#!/usr/bin/env node
// Compiles spec/data/*.json and spec/VERSION into data_gen.go: one Go variable per key of each
// data file, in file order, so no JSON is parsed at run time.
//
//   node go/scripts/gen_data.mjs          write the file
//   node go/scripts/gen_data.mjs --check  exit 1 if the committed file is stale
//
// Shapes: a string array becomes []string, an object of strings []dataKV (file order; JS
// Object.entries order is applied at run time by tables.go), an array of joiner objects
// []dataJoiner, a string a const. Any other shape is an error: extend this script first.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const specDir = resolve(here, "../../spec");
const dataDir = join(specDir, "data");
const outFile = resolve(here, "../data_gen.go");

/** A Go interpreted string literal: printable ASCII as is, everything else escaped. */
function str(s) {
  let out = '"';
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (ch === '"' || ch === "\\") out += `\\${ch}`;
    else if (cp >= 0x20 && cp < 0x7f) out += ch;
    else if (cp <= 0xffff) out += `\\u${cp.toString(16).padStart(4, "0")}`;
    else out += `\\U${cp.toString(16).padStart(8, "0")}`;
  }
  return `${out}"`;
}

const camel = (s) => s.replace(/[-_]([a-z])/g, (_m, c) => c.toUpperCase());
const pascal = (s) => {
  const c = camel(s);
  return c.charAt(0).toUpperCase() + c.slice(1);
};

const JOINER_KEYS = new Set(["raw", "canonical", "kind", "caseSensitive"]);

function fail(where, why) {
  console.error(`gen_data.mjs: ${where}: ${why}; extend go/scripts/gen_data.mjs`);
  process.exit(2);
}

function render() {
  const version = readFileSync(join(specDir, "VERSION"), "utf8").trim();
  const out = [
    "// Code generated by go/scripts/gen_data.mjs from spec/data and spec/VERSION. DO NOT EDIT.",
    "",
    "package trackparse",
    "",
    "// SpecVersion is the version of the spec this module implements.",
    `const SpecVersion = ${str(version)} // x-release-please-version`,
    "",
    "// dataKV is one entry of a JSON object in spec/data, in file order.",
    "type dataKV struct {",
    "\tkey   string",
    "\tvalue string",
    "}",
    "",
    "// dataJoiner is one entry of spec/data/joiners.json.",
    "type dataJoiner struct {",
    "\traw           string",
    "\tcanonical     string",
    "\tkind          string",
    "\tcaseSensitive bool",
    "}",
  ];
  for (const file of readdirSync(dataDir).filter((f) => f.endsWith(".json")).sort()) {
    const data = JSON.parse(readFileSync(join(dataDir, file), "utf8"));
    const stem = file.slice(0, -5);
    for (const [key, v] of Object.entries(data)) {
      if (key === "$comment") continue;
      const name = `data${pascal(stem)}${pascal(key)}`;
      const where = `spec/data/${file} ${key}`;
      out.push("");
      out.push(`// ${name} is ${key} in spec/data/${file}.`);
      if (typeof v === "string") {
        out.push(`const ${name} = ${str(v)}`);
      } else if (Array.isArray(v) && v.every((x) => typeof x === "string")) {
        out.push(`var ${name} = []string{`);
        for (const x of v) out.push(`\t${str(x)},`);
        out.push("}");
      } else if (Array.isArray(v) && v.every((x) => x && typeof x === "object" && !Array.isArray(x))) {
        out.push(`var ${name} = []dataJoiner{`);
        for (const x of v) {
          const fields = [];
          for (const [k, fv] of Object.entries(x)) {
            if (!JOINER_KEYS.has(k)) fail(where, `unknown key ${k}`);
            if (k === "caseSensitive") {
              if (typeof fv !== "boolean") fail(where, "caseSensitive is not a boolean");
              fields.push(`caseSensitive: ${fv}`);
            } else {
              if (typeof fv !== "string") fail(where, `${k} is not a string`);
              fields.push(`${k}: ${str(fv)}`);
            }
          }
          out.push(`\t{${fields.join(", ")}},`);
        }
        out.push("}");
      } else if (v && typeof v === "object" && !Array.isArray(v)) {
        out.push(`var ${name} = []dataKV{`);
        for (const [k, x] of Object.entries(v)) {
          if (k === "$comment") continue;
          if (typeof x !== "string") fail(where, `value of ${k} is not a string`);
          out.push(`\t{${str(k)}, ${str(x)}},`);
        }
        out.push("}");
      } else {
        fail(where, "unsupported shape");
      }
    }
  }
  return `${out.join("\n")}\n`;
}

const content = render();
let current = "";
try {
  current = readFileSync(outFile, "utf8");
} catch {}
if (process.argv.includes("--check")) {
  if (current !== content) {
    console.error("go/data_gen.go is stale: run node go/scripts/gen_data.mjs");
    process.exit(1);
  }
} else if (current !== content) {
  writeFileSync(outFile, content);
  console.log(`wrote ${outFile}`);
}
