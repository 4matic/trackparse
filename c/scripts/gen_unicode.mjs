#!/usr/bin/env node
// Writes c/src/unicode_gen.h and c/src/unicode_gen.c: the Unicode tables of the C port, all taken
// from the JS reference engine (Node), so the library's Unicode version is Node's, never the C
// library's or the platform's. The same tables as go/unicode_gen.go (the derivation is shared
// with go/scripts/gen_unicode.mjs through unicode_derive.mjs; its header comment explains the
// combining class ranks):
//
//   - general categories L and Lu (SPEC R0.6): /\p{L}/u and /\p{Lu}/u, as range tables;
//   - String.prototype.toLowerCase() (R0.4 dedup key): runs of code points with a common delta,
//     the multi-code-point results, and the properties Cased and Case_Ignorable that the
//     final-sigma rule reads;
//   - String.prototype.normalize("NFC" | "NFD") (R1, R0.4): full canonical decompositions,
//     canonical combining class ranks, composition pairs and the NFC quick-check sets. Hangul
//     syllables are left to the algorithm in unicode.c.
//
//   node c/scripts/gen_unicode.mjs                 write the tables and the test sample
//   node c/scripts/gen_unicode.mjs --check         exit 1 if any of them is stale
//   node c/scripts/gen_unicode.mjs --cases <dir>   write the exhaustive cases to <dir>/cases.jsonl
import * as fs from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PRIVATE_DATA, cStr, cTpStr } from "./c_lit.mjs";
import { UNICODE, cases, tables } from "./unicode_derive.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const cDir = resolve(here, "..");

const hex = (n) => `0x${n.toString(16)}`;
const GENERATED = [
  "/* Code generated by c/scripts/gen_unicode.mjs; DO NOT EDIT.",
  " * Run `node c/scripts/gen_unicode.mjs` to regenerate.",
  " *",
  " * Tables taken from the JS reference engine (Node), so the Unicode version is Node's and not",
  " * the platform's: categories L and Lu (R0.6), toLowerCase() (R0.4) and NFC/NFD (R1, R0.4).",
  " * The method behind the combining class ranks is described in c/scripts/unicode_derive.mjs",
  " * and go/scripts/gen_unicode.mjs. */",
  `/* Unicode ${UNICODE} */`,
];

/** Initializer elements, as many to a line as fit in 100 columns (at most `perLine`). */
function rows(items, perLine) {
  const lines = [];
  let line = [];
  const width = (l) => 2 + l.reduce((w, x) => w + x.length + 2, 0) - 1;
  for (const item of items) {
    if (line.length > 0 && (line.length === perLine || width([...line, item]) > 100)) {
      lines.push(`  ${line.join(", ")},`);
      line = [];
    }
    line.push(item);
  }
  if (line.length > 0) lines.push(`  ${line.join(", ")},`);
  return lines.join("\n");
}

function render(t) {
  const h = [
    ...GENERATED,
    "#ifndef TP_UNICODE_GEN_H",
    "#define TP_UNICODE_GEN_H",
    "",
    '#include "unicode.h"',
    "",
    ...PRIVATE_DATA,
    "",
    "/* The Unicode version of Node's tables these were generated from. */",
    `#define TP_UNICODE_VERSION ${cStr(UNICODE)}`,
  ];
  const c = [...GENERATED, '#include "unicode_gen.h"'];
  const table = (type, name, doc, items, perLine) => {
    const count = `${name.toUpperCase()}_N`;
    h.push("", `/* ${name}: ${doc} */`, `#define ${count} ${items.length}`);
    h.push(`TP_PRIVATE_DATA const ${type} ${name}[${count}];`);
    c.push("", `TP_PRIVATE const ${type} ${name}[${count}] = {`, rows(items, perLine), "};");
  };
  const ranges = (name, doc, rs) =>
    table("tp_uni_range", name, doc, rs.map(([a, b]) => `{${hex(a)}, ${hex(b)}}`), 6);

  const { runs, multi } = t.lower;
  const n = t.norm;
  ranges("tp_uni_letter", "general category L (Lu, Ll, Lt, Lm, Lo), JS /\\p{L}/u.", t.letter);
  ranges("tp_uni_upper", "general category Lu, JS /\\p{Lu}/u.", t.upper);
  ranges("tp_uni_cased", "property Cased, read by the final-sigma rule.", t.cased);
  ranges("tp_uni_case_ignorable", "property Case_Ignorable, read by the final-sigma rule.", t.ignorable);
  table(
    "tp_lower_run",
    "tp_uni_lower",
    "JS toLowerCase() of one code point. Every first + k*step <= last maps\n * to itself plus delta. Sorted by first, no overlaps.",
    runs.map((r) => `{${hex(r.first)}, ${hex(r.last)}, ${r.step}, ${r.delta}}`),
    4,
  );
  table(
    "tp_lower_multi",
    "tp_uni_lower_multi",
    "code points whose lowercase is several code points (UTF-8). Sorted.",
    multi.map(([cp, to]) => `{${hex(cp)}, ${cTpStr(to)}}`),
    3,
  );
  table(
    "tp_ccc_range",
    "tp_uni_ccc",
    "canonical combining class ranks of the code points that are their own NFD; 0\n * when absent. Ranks keep the order and equality of the classes, which is all normalization\n * uses.",
    n.cccRanges.map(([a, b, r]) => `{${hex(a)}, ${hex(b)}, ${r}}`),
    5,
  );
  // Decompositions: offsets into one pool of code points.
  const pool = [];
  const entries = [];
  for (const [cp, d] of n.decomp) {
    entries.push(`{${hex(cp)}, ${pool.length}, ${d.length}}`);
    pool.push(...d);
  }
  if (pool.length > 0xffff) throw new Error("decomposition pool does not fit uint16_t offsets");
  table(
    "tp_decomp_entry",
    "tp_uni_decomp",
    "full canonical decomposition (NFD) of every code point that has one, except\n * the Hangul syllables: tp_uni_decomp_pool[off .. off+len). Sorted by code point.",
    entries,
    5,
  );
  table("tp_rune", "tp_uni_decomp_pool", "the code points of tp_uni_decomp.", pool.map(hex), 10);
  table(
    "tp_compose_pair",
    "tp_uni_compose",
    "canonical composition pairs (first, second) -> primary composite, without\n * the Hangul syllables and the composition exclusions. Sorted by first, then second.",
    n.pairs.map(([a, b, x]) => `{${hex(a)}, ${hex(b)}, ${hex(x)}}`),
    4,
  );
  ranges("tp_uni_nfc_no", "code points that NFC changes on their own (NFC_Quick_Check=No).", n.nfcNo);
  ranges(
    "tp_uni_compose_second",
    "code points that can compose with what precedes them\n * (NFC_Quick_Check=Maybe).",
    n.second,
  );
  h.push(
    "",
    "/* Every code point below it is a starter that neither normalization form changes and that",
    " * never composes with what precedes it. */",
    `#define TP_UNI_QUICK_MIN ${hex(n.quickMin)}`,
    "",
    "#endif /* TP_UNICODE_GEN_H */",
  );
  return { h: `${h.join("\n")}\n`, c: `${c.join("\n")}\n` };
}

const args = process.argv.slice(2);
const casesAt = args.indexOf("--cases");
if (casesAt >= 0) {
  const dir = args[casesAt + 1];
  if (!dir) throw new Error("--cases needs a directory");
  fs.mkdirSync(dir, { recursive: true });
  const lines = [];
  let bytes = 0;
  const path = join(dir, "cases.jsonl");
  fs.writeFileSync(path, "");
  for (const line of cases(tables(), true)) {
    lines.push(line);
    bytes += line.length;
    if (bytes > 1 << 22) {
      fs.writeFileSync(path, `${lines.join("\n")}\n`, { flag: "a" });
      lines.length = 0;
      bytes = 0;
    }
  }
  fs.writeFileSync(path, `${lines.join("\n")}\n`, { flag: "a" });
  fs.writeFileSync(join(dir, "unicode-version.txt"), `${UNICODE}\n`);
  console.log(`wrote ${path}`);
} else {
  const check = args.includes("--check");
  const t = tables();
  const out = render(t);
  let stale = false;
  const emit = (rel, content) => {
    const path = join(cDir, rel);
    let current = "";
    try {
      current = fs.readFileSync(path, "utf8");
    } catch {}
    if (check) {
      // The tables depend on Node's Unicode version: only compare like with like.
      let gen = "";
      try {
        gen = fs.readFileSync(join(cDir, "src", "unicode_gen.h"), "utf8");
      } catch {}
      const other = gen.match(/^\/\* Unicode (\S+) \*\/$/m);
      if (other && other[1] !== UNICODE) {
        console.log(`c/${rel}: skipped (Unicode ${UNICODE} here)`);
        return;
      }
      if (current !== content) {
        console.error(`c/${rel} is stale: run node c/scripts/gen_unicode.mjs`);
        stale = true;
      }
    } else if (current !== content) {
      fs.mkdirSync(dirname(path), { recursive: true });
      fs.writeFileSync(path, content);
      console.log(`wrote ${path}`);
    }
  };
  emit("src/unicode_gen.h", out.h);
  emit("src/unicode_gen.c", out.c);
  emit("tests/data/unicode/cases.jsonl", `${[...cases(t, false)].join("\n")}\n`);
  if (stale) process.exit(1);
}
