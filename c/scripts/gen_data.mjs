#!/usr/bin/env node
// Compiles spec/data/*.json and spec/VERSION into src/data_gen.h and src/data_gen.c: one C array
// per key of each data file, in file order, so no JSON is parsed at run time. The C twin of
// go/scripts/gen_data.mjs (same names, snake_case: dataFeatMarkersMarkers is
// tp_data_feat_markers_markers).
//
//   node c/scripts/gen_data.mjs          write the files
//   node c/scripts/gen_data.mjs --check  exit 1 if a committed file is stale
//
// Shapes: a string array becomes `const tp_str x[N]`, an object of strings `const tp_data_kv
// x[N]` (file order; JS Object.entries order is applied at run time by tables.c), an array of
// joiner objects `const tp_data_joiner x[N]`, a string a TP_S(...) macro. Each array has a
// TP_DATA_..._N count macro. Any other shape is an error: extend this script first.
import * as fs from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PRIVATE_DATA, cStr, cTpStr, emitFile, snake } from "./c_lit.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const specDir = resolve(here, "../../spec");
const dataDir = join(specDir, "data");
const srcDir = resolve(here, "../src");

const JOINER_KEYS = ["raw", "canonical", "kind", "caseSensitive"];
const GENERATED = "/* Code generated by c/scripts/gen_data.mjs from spec/data and spec/VERSION. DO NOT EDIT. */";

/** `a b` on one line when it fits in 100 columns, else b on a continuation line. */
const wrap = (a, b) => (a.length + 1 + b.length <= 100 ? `${a} ${b}` : `${a}\n    ${b}`);

function fail(where, why) {
  console.error(`gen_data.mjs: ${where}: ${why}; extend c/scripts/gen_data.mjs`);
  process.exit(2);
}

function render() {
  const version = fs.readFileSync(join(specDir, "VERSION"), "utf8").trim();
  const h = [
    GENERATED,
    "#ifndef TP_DATA_GEN_H",
    "#define TP_DATA_GEN_H",
    "",
    '#include "rt.h"',
    "",
    ...PRIVATE_DATA,
    "",
    "/* The version of the spec this library implements. */",
    `#define TP_SPEC_VERSION ${cStr(version)} /* x-release-please-version */`,
    "",
    "/* One entry of a JSON object in spec/data, in file order. */",
    "typedef struct tp_data_kv {",
    "  tp_str key;",
    "  tp_str value;",
    "} tp_data_kv;",
    "",
    "/* One entry of spec/data/joiners.json. */",
    "typedef struct tp_data_joiner {",
    "  tp_str raw;",
    "  tp_str canonical;",
    "  tp_str kind;",
    "  bool case_sensitive;",
    "} tp_data_joiner;",
  ];
  const c = [GENERATED, '#include "data_gen.h"'];
  for (const file of fs.readdirSync(dataDir).filter((f) => f.endsWith(".json")).sort()) {
    const data = JSON.parse(fs.readFileSync(join(dataDir, file), "utf8"));
    const stem = file.slice(0, -5);
    for (const [key, v] of Object.entries(data)) {
      if (key === "$comment") continue;
      const name = `tp_data_${snake(stem)}_${snake(key)}`;
      const count = `${name.toUpperCase()}_N`;
      const where = `spec/data/${file} ${key}`;
      const array = (type, items) => {
        if (items.length === 0) fail(where, "empty list (a C array cannot be empty)");
        h.push("", `/* ${key} in spec/data/${file}. */`);
        h.push(`#define ${count} ${items.length}`);
        h.push(wrap(`TP_PRIVATE_DATA const ${type}`, `${name}[${count}];`));
        c.push("", wrap(`TP_PRIVATE const ${type}`, `${name}[${count}] = {`));
        for (const item of items) c.push(`  ${item},`);
        c.push("};");
      };
      if (typeof v === "string") {
        h.push("", `/* ${key} in spec/data/${file}. */`);
        h.push(`#define ${name.toUpperCase()} TP_S(${cStr(v)})`);
      } else if (Array.isArray(v) && v.every((x) => typeof x === "string")) {
        array("tp_str", v.map(cTpStr));
      } else if (Array.isArray(v) && v.every((x) => x && typeof x === "object" && !Array.isArray(x))) {
        const items = v.map((x) => {
          for (const [k, fv] of Object.entries(x)) {
            if (!JOINER_KEYS.includes(k)) fail(where, `unknown key ${k}`);
            if (k === "caseSensitive" ? typeof fv !== "boolean" : typeof fv !== "string") {
              fail(where, `${k} has the wrong type`);
            }
          }
          const s = (k) => cTpStr(x[k] ?? "");
          return `{${s("raw")}, ${s("canonical")}, ${s("kind")}, ${x.caseSensitive ? "true" : "false"}}`;
        });
        array("tp_data_joiner", items);
      } else if (v && typeof v === "object" && !Array.isArray(v)) {
        const items = [];
        for (const [k, x] of Object.entries(v)) {
          if (k === "$comment") continue;
          if (typeof x !== "string") fail(where, `value of ${k} is not a string`);
          items.push(`{${cTpStr(k)}, ${cTpStr(x)}}`);
        }
        array("tp_data_kv", items);
      } else {
        fail(where, "unsupported shape");
      }
    }
  }
  h.push("", "#endif /* TP_DATA_GEN_H */");
  return { h: `${h.join("\n")}\n`, c: `${c.join("\n")}\n` };
}

const check = process.argv.includes("--check");
const out = render();
let stale = emitFile(fs, join(srcDir, "data_gen.h"), out.h, check, "c/src/data_gen.h");
stale = emitFile(fs, join(srcDir, "data_gen.c"), out.c, check, "c/src/data_gen.c") || stale;
if (check && stale) process.exit(1);
